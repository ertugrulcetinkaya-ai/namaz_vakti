#!/usr/bin/env python3
"""Generate the Diyanet district table from the checked-in API snapshot."""
import json
from pathlib import Path
import unicodedata

ROOT = Path(__file__).resolve().parents[2]
SNAPSHOT = ROOT / 'tools/diyanet_snapshot'
OUTPUT = ROOT / 'app/src/main/java/com/example/namazvakti/domain/model/DiyanetDistricts.kt'

def normalize(value):
    return unicodedata.normalize('NFC', value).replace('I', 'ı').replace('İ', 'i').lower()

def load(path):
    return json.loads(path.read_text(encoding='utf-8'))

def quote(value):
    return json.dumps(value, ensure_ascii=False)

provinces = load(SNAPSHOT / 'sehirler_2.json')
assert len(provinces) == 81
lines = ['package com.example.namazvakti.domain.model', '', '// Generated by tools/diyanet_locations/generate.py; do not edit.', 'object DiyanetDistricts {', '    data class District(val provinceId: String, val provinceName: String, val id: String, val name: String)', '    data class Province(val id: String, val name: String, val centralDistrictId: String)', '', '    val provinces = listOf(']
districts = []
for province in provinces:
    pid, name = province['SehirID'], province['SehirAdi']
    entries = load(SNAPSHOT / 'ilceler' / (pid + '.json'))
    matches = [d for d in entries if normalize(d['IlceAdi']) == normalize(name)]
    if len(matches) != 1:
        raise ValueError(f'{name}: expected one central district, got {len(matches)}')
    lines.append(f'        Province({quote(pid)}, {quote(name)}, {quote(matches[0]["IlceID"])}),')
    districts.extend((pid, name, d['IlceID'], d['IlceAdi']) for d in entries)
assert len(districts) == 869
lines += ['    )', '', '    val districts = listOf(']
lines += ['        District(' + ', '.join(map(quote, d)) + '),' for d in districts]
lines += ['    )', '', '    fun forCity(city: String, country: String): Province? {', '        val option = PrayerLocationConfig.cityOptions.firstOrNull { it.city == city && it.country == country }', '            ?: return null', '        return provinces.firstOrNull { it.name == option.displayCity }', '    }', '}', '']
OUTPUT.write_text('\n'.join(lines), encoding='utf-8')
